CREATE TABLE usuarios (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(120) NOT NULL,
    email       VARCHAR(160) NOT NULL,
    senha_hash  VARCHAR(100) NOT NULL,
    perfil      VARCHAR(20)  NOT NULL CHECK (perfil IN ('ADMIN', 'VENDEDOR')),
    ativo       BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_usuarios_email ON usuarios (lower(email));

CREATE TABLE categorias (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(80) NOT NULL
);
CREATE UNIQUE INDEX uk_categorias_nome ON categorias (lower(nome));

CREATE TABLE produtos (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku                 VARCHAR(40)   NOT NULL,
    nome                VARCHAR(150)  NOT NULL,
    descricao           VARCHAR(500),
    categoria_id        BIGINT        NOT NULL REFERENCES categorias (id),
    preco_custo         NUMERIC(12,2) NOT NULL CHECK (preco_custo >= 0),
    preco_venda         NUMERIC(12,2) NOT NULL CHECK (preco_venda >= 0),
    quantidade_estoque  INTEGER       NOT NULL DEFAULT 0 CHECK (quantidade_estoque >= 0),
    estoque_minimo      INTEGER       NOT NULL DEFAULT 0 CHECK (estoque_minimo >= 0),
    ativo               BOOLEAN       NOT NULL DEFAULT TRUE,
    versao              BIGINT        NOT NULL DEFAULT 0,
    criado_em           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em       TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_produtos_sku ON produtos (lower(sku));
CREATE INDEX idx_produtos_categoria ON produtos (categoria_id);

CREATE TABLE vendas (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   BIGINT        NOT NULL REFERENCES usuarios (id),
    data_venda   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    valor_total  NUMERIC(14,2) NOT NULL CHECK (valor_total >= 0),
    status       VARCHAR(20)   NOT NULL CHECK (status IN ('CONCLUIDA', 'CANCELADA'))
);
CREATE INDEX idx_vendas_data ON vendas (data_venda);

CREATE TABLE itens_venda (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venda_id        BIGINT        NOT NULL REFERENCES vendas (id) ON DELETE CASCADE,
    produto_id      BIGINT        NOT NULL REFERENCES produtos (id),
    quantidade      INTEGER       NOT NULL CHECK (quantidade > 0),
    preco_unitario  NUMERIC(12,2) NOT NULL CHECK (preco_unitario >= 0),
    subtotal        NUMERIC(14,2) NOT NULL CHECK (subtotal >= 0)
);
CREATE INDEX idx_itens_venda_venda ON itens_venda (venda_id);
CREATE INDEX idx_itens_venda_produto ON itens_venda (produto_id);

CREATE TABLE movimentacoes_estoque (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id         BIGINT       NOT NULL REFERENCES produtos (id),
    tipo               VARCHAR(10)  NOT NULL CHECK (tipo IN ('ENTRADA', 'SAIDA')),
    quantidade         INTEGER      NOT NULL CHECK (quantidade > 0),
    motivo             VARCHAR(200) NOT NULL,
    usuario_id         BIGINT       NOT NULL REFERENCES usuarios (id),
    venda_id           BIGINT       REFERENCES vendas (id),
    data_movimentacao  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_movimentacoes_produto_data ON movimentacoes_estoque (produto_id, data_movimentacao DESC);
